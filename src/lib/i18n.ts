export type Language = "hi-roman" | "hi";

export const LANGUAGES: { code: Language; label: string }[] = [
  { code: "hi-roman", label: "Hinglish" },
  { code: "hi", label: "हिन्दी" },
];

const LANG_KEY = "ms-lang";

export function getLanguage(): Language {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === "hi" ? "hi" : "hi-roman";
  } catch {
    return "hi-roman";
  }
}

export function setLanguage(l: Language): void {
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    // ignore storage failures; language just falls back to Hinglish
  }
}

